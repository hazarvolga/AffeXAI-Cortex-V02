import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import test from 'node:test';
test('mention keyboard navigation and virtualized log window', async () => {
const frontendRequire = createRequire(import.meta.url);
const React = frontendRequire('react');
const { createRoot } = frontendRequire('react-dom/client');
// Reuse the installed DOMPurify server DOM dependency; no separate test installation.
const domRequire = createRequire(frontendRequire.resolve('isomorphic-dompurify'));
const { JSDOM } = domRequire('jsdom');
const dom = new JSDOM('<div id="root"></div>');
Object.assign(globalThis, { window: dom.window, document: dom.window.document, HTMLElement: dom.window.HTMLElement, React, IS_REACT_ACT_ENVIRONMENT: true });
Object.defineProperty(globalThis, 'navigator', { configurable: true, value: dom.window.navigator });
const { MentionList } = await import('../rich-text-editor.tsx');
const container = document.getElementById('root');
const root = createRoot(container);
const ref = React.createRef();
const chosen = [];
const items = [{ id: 'a', label: 'Alpha' }, { id: 'b', label: 'Beta' }];
const render = async (list) => React.act(async () => root.render(React.createElement(MentionList, { ref, items: list, command: (item) => chosen.push(item.id) })));
const key = async (value) => { let handled = false; await React.act(async () => { handled = ref.current.onKeyDown({ event: new dom.window.KeyboardEvent('keydown', { key: value }) }); }); return handled; };
await render(items);
await React.act(async () => document.dispatchEvent(new dom.window.KeyboardEvent('keydown', { key: 'ArrowDown' })));
await key('Enter');
assert.deepEqual(chosen, ['a'], 'document listener must not navigate a second time');
await key('ArrowDown');
await key('Enter');
assert.deepEqual(chosen, ['a', 'b']);
await key('ArrowDown');
await key('Enter');
assert.deepEqual(chosen, ['a', 'b', 'a'], 'navigation wraps');
await render([]);
assert.equal(await key('ArrowDown'), false);
assert.equal(await key('Enter'), false);
await render([{ id: 'c', label: 'Gamma' }]);
await key('Enter');
assert.equal(chosen.at(-1), 'c', 'new query resets selected index');
assert.equal(await key('x'), false);
await React.act(async () => root.unmount());
const { LogsConsole } = await import('../logs/LogsConsole.tsx');
const { renderToStaticMarkup } = frontendRequire('react-dom/server');
const logs = Array.from({ length: 1000 }, (_, index) => ({ id: String(index), timestamp: '2026-10-07T10:00:00Z', level: 'INFO', context: 'test', message: 'Virtualized log ' + index }));
const markup = renderToStaticMarkup(React.createElement(LogsConsole, { logs }));
const renderedRows = (markup.match(/role="listitem"/g) || []).length;
assert.ok(renderedRows > 0 && renderedRows < 100, '1000 logs should render only a small visible window');
assert.ok(markup.includes('aria-setsize="1000"'));
console.log('PASS: log virtualization renders ' + renderedRows + ' rows for 1000 entries');
console.log('PASS: mention ref navigation, no global listener, wrap, empty results, refreshed items, unhandled keys');

 dom.window.close();
});
